/** Filter any level array by difficulty (1 = easy, 2 = medium, 3 = hard). */
export function byDiff(arr, diff){
  if (!diff || diff === 'all') return arr;
  const f = arr.filter(x => x.diff === diff);
  return f.length ? f : arr;
}

/** Filter by language and difficulty together. */
export function pick(arr, lang = 'all', diff = 'all'){
  return byDiff(byLang(arr, lang), diff);
}

/** Fisher-Yates shuffle (returns a new array). */
export function shuffled(arr){
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--){
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

